#!/usr/bin/env python3
"""Generate the BioKids xfwm4 theme: a child-sized title bar and a big close button.

D-163. Until then a child's windows had no buttons at all (`button_layout` was
`|`) and a maximised window had no title bar either, so an app that filled the
screen - Stellarium, which starts full screen - could only be left through its
own menus, if it had any. A six-year-old could not find the way out, and
neither, on the first try, could the owner.

So every app window gets a 64-pixel title bar with one button on it: a large
coral square with a white cross, always in the same place, the top right corner
of the screen (the launcher maximises every app window). 64 x 64 is the
smallest target UX.md section 2.4 allows for a four-year-old.

Same tiny PNG writer as `make_icons.py`, with an alpha channel. The output is
committed; a build does not run this.
"""

from __future__ import annotations

import struct
import sys
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
THEME = ROOT / "src" / "biokids_shell" / "xfce" / "theme" / "BioKids" / "xfwm4"

TITLE_HEIGHT = 64
BORDER = 4
CLOSE_WIDTH = 76
CLOSE_SIZE = 56
CLOSE_RADIUS = 15
CROSS_HALF = 13
CROSS_THICKNESS = 7.0
SUPERSAMPLE = 4

Rgba = tuple[int, int, int, int]

BACKGROUND: Rgba = (251, 247, 242, 255)  # --bg
LINE: Rgba = (231, 222, 213, 255)  # --line
TRANSPARENT: Rgba = (0, 0, 0, 0)
WHITE: Rgba = (255, 255, 255, 255)
# --danger and two darker steps. White on #E04A3F is 4:1, which a 56-pixel
# symbol needs (WCAG 1.4.11 asks 3:1 of a control); --bio-coral would be 2.9:1.
CLOSE_FILL = {
    "active": (224, 74, 63, 255),
    "inactive": (224, 74, 63, 255),
    "prelight": (201, 58, 48, 255),
    "pressed": (176, 48, 40, 255),
}

#: Buttons xfwm4 loads whether or not the layout shows them. The layout shows
#: only the close button; the others are transparent slivers so that a theme
#: switch never falls back to the Default theme's small icons.
UNUSED_BUTTONS = (
    "hide",
    "maximize",
    "maximize-toggled",
    "menu",
    "shade",
    "shade-toggled",
    "stick",
    "stick-toggled",
)
BUTTON_STATES = ("active", "inactive", "prelight", "pressed")

THEMERC = """\
# BioKids xfwm4 theme (D-163). Generated by dev/make_xfwm4_theme.py.
active_text_color=#221E1C
inactive_text_color=#6B625C
button_offset=4
button_spacing=0
full_width_title=true
maximized_offset=0
show_app_icon=false
title_horizontal_offset=12
title_shadow_active=false
title_shadow_inactive=false
title_vertical_offset_active=0
title_vertical_offset_inactive=0
"""


def write_png(path: Path, width: int, height: int, pixels: list[list[Rgba]]) -> None:
    raw = bytearray()
    for row in pixels:
        raw.append(0)
        for r, g, b, a in row:
            raw += bytes((r, g, b, a))

    def chunk(tag: bytes, data: bytes) -> bytes:
        return (
            struct.pack(">I", len(data))
            + tag
            + data
            + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)
        )

    header = struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0)  # 8-bit RGBA
    path.write_bytes(
        b"\x89PNG\r\n\x1a\n"
        + chunk(b"IHDR", header)
        + chunk(b"IDAT", zlib.compress(bytes(raw), 9))
        + chunk(b"IEND", b"")
    )


def solid(width: int, height: int, colour: Rgba) -> list[list[Rgba]]:
    return [[colour] * width for _ in range(height)]


def title_strip(width: int) -> list[list[Rgba]]:
    """The bar's background, with a two-pixel line along its bottom edge."""
    return [
        [LINE if y >= TITLE_HEIGHT - 2 else BACKGROUND] * width for y in range(TITLE_HEIGHT)
    ]


def _inside_rounded_square(x: float, y: float, left: float, top: float) -> bool:
    right, bottom = left + CLOSE_SIZE, top + CLOSE_SIZE
    if not (left <= x <= right and top <= y <= bottom):
        return False
    cx = min(max(x, left + CLOSE_RADIUS), right - CLOSE_RADIUS)
    cy = min(max(y, top + CLOSE_RADIUS), bottom - CLOSE_RADIUS)
    return (x - cx) ** 2 + (y - cy) ** 2 <= CLOSE_RADIUS**2


def _on_cross(x: float, y: float, cx: float, cy: float) -> bool:
    """Two strokes at 45 degrees with round ends."""
    dx, dy = x - cx, y - cy
    for sx in (1.0, -1.0):
        # Distance from the segment from (-h, -h*sx) to (h, h*sx).
        t = max(-CROSS_HALF, min(CROSS_HALF, (dx + dy * sx) / 2))
        px, py = t, t * sx
        if (dx - px) ** 2 + (dy - py) ** 2 <= (CROSS_THICKNESS / 2) ** 2:
            return True
    return False


def close_button(fill: Rgba) -> list[list[Rgba]]:
    left = (CLOSE_WIDTH - CLOSE_SIZE) / 2
    top = (TITLE_HEIGHT - 2 - CLOSE_SIZE) / 2
    cx, cy = left + CLOSE_SIZE / 2, top + CLOSE_SIZE / 2
    rows: list[list[Rgba]] = []
    for y in range(TITLE_HEIGHT):
        row: list[Rgba] = []
        for x in range(CLOSE_WIDTH):
            base = LINE if y >= TITLE_HEIGHT - 2 else BACKGROUND
            hits_square = hits_cross = 0
            for sy in range(SUPERSAMPLE):
                for sx in range(SUPERSAMPLE):
                    fx = x + (sx + 0.5) / SUPERSAMPLE
                    fy = y + (sy + 0.5) / SUPERSAMPLE
                    if _inside_rounded_square(fx, fy, left, top):
                        hits_square += 1
                        if _on_cross(fx, fy, cx, cy):
                            hits_cross += 1
            total = SUPERSAMPLE * SUPERSAMPLE
            square = hits_square / total
            cross = hits_cross / total
            pixel = tuple(
                round(b * (1 - square) + f * (square - cross) + w * cross)
                for b, f, w in zip(base[:3], fill[:3], WHITE[:3], strict=True)
            )
            row.append((pixel[0], pixel[1], pixel[2], 255))
        rows.append(row)
    return rows


def main() -> int:
    THEME.mkdir(parents=True, exist_ok=True)
    (THEME / "themerc").write_text(THEMERC, encoding="utf-8", newline="\n")

    for state in ("active", "inactive"):
        for n in range(1, 6):
            write_png(THEME / f"title-{n}-{state}.png", 8, TITLE_HEIGHT, title_strip(8))
        for corner in ("top-left", "top-right"):
            write_png(
                THEME / f"{corner}-{state}.png", BORDER, TITLE_HEIGHT, title_strip(BORDER)
            )
        write_png(THEME / f"left-{state}.png", BORDER, 8, solid(BORDER, 8, LINE))
        write_png(THEME / f"right-{state}.png", BORDER, 8, solid(BORDER, 8, LINE))
        write_png(THEME / f"bottom-{state}.png", 8, BORDER, solid(8, BORDER, LINE))
        for corner in ("bottom-left", "bottom-right"):
            write_png(
                THEME / f"{corner}-{state}.png", BORDER, BORDER, solid(BORDER, BORDER, LINE)
            )

    for state in BUTTON_STATES:
        write_png(
            THEME / f"close-{state}.png",
            CLOSE_WIDTH,
            TITLE_HEIGHT,
            close_button(CLOSE_FILL[state]),
        )
        for button in UNUSED_BUTTONS:
            write_png(
                THEME / f"{button}-{state}.png",
                1,
                TITLE_HEIGHT,
                solid(1, TITLE_HEIGHT, TRANSPARENT),
            )

    print(f"wrote {sum(1 for _ in THEME.iterdir())} files to {THEME}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
